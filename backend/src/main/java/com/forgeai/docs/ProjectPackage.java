package com.forgeai.docs;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

import org.springframework.stereotype.Component;

import com.forgeai.code.CodeService.SourceFile;
import com.forgeai.design.DesignExport;
import com.forgeai.design.api.OpenApiExporter;
import com.forgeai.design.database.SqlExporter;
import com.forgeai.docs.DocsDtos.Source;

import tools.jackson.databind.json.JsonMapper;

/**
 * The full project package: the accepted code, the README and developer guide, and documents
 * derived from the approved design (requirements, architecture, data model with SQL schema, API
 * reference with OpenAPI document, backlog). A document replaces an accepted file at the same path.
 */
@Component
class ProjectPackage {

    static final String REQUIREMENTS = "docs/requirements.md";
    static final String ARCHITECTURE = "docs/architecture.md";
    static final String DATA_MODEL = "docs/data-model.md";
    static final String SQL = "docs/database.sql";
    static final String API_REFERENCE = "docs/api-reference.md";
    static final String OPENAPI = "docs/openapi.json";
    static final String BACKLOG = "docs/backlog.md";

    private final JsonMapper jsonMapper;

    ProjectPackage(JsonMapper jsonMapper) {
        this.jsonMapper = jsonMapper;
    }

    /** One file of the package. */
    record File(String path, Source source, String content, boolean replacesCode) {
    }

    /** The package's files, sorted by path. Needs complete inputs (no blocker). */
    List<File> files(DocsInputs inputs, List<ProjectDocument> documents) {
        Map<String, File> files = new LinkedHashMap<>();
        for (SourceFile file : inputs.files()) {
            files.put(file.path(), new File(file.path(), Source.CODE, file.content(), false));
        }
        Map<String, String> generated = new LinkedHashMap<>();
        for (ProjectDocument document : documents) generated.put(document.getKind().path(), document.getContent());
        String name = inputs.project().name();
        generated.put(REQUIREMENTS, DesignMarkdown.requirements(name, inputs.requirements().approved()));
        generated.put(ARCHITECTURE, DesignMarkdown.architecture(name, inputs.architecture().content()));
        generated.put(DATA_MODEL, DesignMarkdown.dataModel(name, inputs.database().content()));
        generated.put(SQL, SqlExporter.export(inputs.database().content(), List.of(
                "PostgreSQL schema for \"" + name + "\"",
                "Generated by ForgeAI from the approved database design")));
        generated.put(API_REFERENCE, DesignMarkdown.apiReference(name, inputs.api().content()));
        generated.put(OPENAPI, jsonMapper.writerWithDefaultPrettyPrinter()
                .writeValueAsString(OpenApiExporter.export(inputs.api().content(), name + " API", "approved design")) + "\n");
        if (!inputs.tasks().isEmpty()) generated.put(BACKLOG, DesignMarkdown.backlog(name, inputs.tasks()));

        for (Map.Entry<String, String> entry : generated.entrySet()) {
            String path = entry.getKey();
            Source source = documents.stream().anyMatch(d -> d.getKind().path().equals(path)) ? Source.DOCUMENT : Source.DESIGN;
            files.put(path, new File(path, source, entry.getValue(), files.containsKey(path)));
        }
        List<File> sorted = new ArrayList<>(files.values());
        sorted.sort(Comparator.comparing(File::path));
        return sorted;
    }

    static String fileName(String projectName) {
        return DesignExport.slug(projectName) + "-package.zip";
    }

    /** The files as a ZIP archive, inside a folder named after the project. */
    static byte[] zip(String projectName, List<File> files) {
        String folder = DesignExport.slug(projectName);
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        try (ZipOutputStream zip = new ZipOutputStream(bytes, StandardCharsets.UTF_8)) {
            for (File file : files) {
                zip.putNextEntry(new ZipEntry(folder + "/" + file.path()));
                zip.write(file.content().getBytes(StandardCharsets.UTF_8));
                zip.closeEntry();
            }
        } catch (IOException ex) {
            throw new UncheckedIOException("Could not build the archive", ex);
        }
        return bytes.toByteArray();
    }
}
